"""Write results/extra.tex: the design constants, counts and the one external sentence numbers.tex lacks.

    python paper/results/make_extra.py [--repo DIR] [--out FILE]

Every value is read from a repository file (named in the % comment above its macro), never typed.
"""
from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
from numfmt import Out, intc  # noqa: E402

SIZE = {"100": "Hund", "150": "HundFifty", "250": "TwoFifty", "500": "FiveHund", "1000": "OneK",
        "2000": "TwoK"}
MAIN = ("higgs", "bank", "elec2")


def const(path: Path, name: str):
    """A module-level constant, read without importing the module."""
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{name} not in {path}")


def section(text: str, head: str) -> str:
    m = re.search(rf"^## {re.escape(head)}.*?$(.*?)(?=^## |\Z)", text, re.S | re.M)
    return m.group(1)


def latex_escape(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for ch in "%&#_$":
        s = s.replace(ch, "\\" + ch)
    s = re.sub(r"kappa = 1", r"$\\kappa = 1$", s)
    return s


def confirm(o: Out, path: Path) -> None:
    """Macros from confirm_1se.json (the fresh-draw confirmation of the one-SE rule)."""
    o.c(f"paper/results/confirm_1se.json (from confirm_1se.py): paired log-loss, rule minus arm")
    d = json.loads(path.read_text())
    o.m("nCfRepeats", str(len(d["repeats"])))
    arms = {"FreeRule": "v_free_1se", "Free": "a4_ref_feature_x100", "Ref": "a2_ref",
            "KOneRule": "v_k1_1se", "Plain": "a1_plain"}
    for n, rec in d["by_n_train"].items():
        for tag, arm in arms.items():
            p = rec["paired"][f"v_kappa_1se - {arm}"]["logloss"]
            o.m(f"nCf{SIZE[n]}D{tag}", sgn4(p["mean"]))
            o.m(f"nCf{SIZE[n]}D{tag}Se", f4(p["se"]))
        ks = [c["kappa"] for c in rec["choices"]["v_kappa_1se"]]
        o.m(f"nCf{SIZE[n]}KappaOnes", f"{sum(k == 1 for k in ks)}/{len(ks)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=str(REPO))
    ap.add_argument("--out", default=str(HERE / "extra.tex"))
    a = ap.parse_args()
    repo = Path(a.repo)
    res = repo / "bench" / "results"
    o = Out()
    o.c("Generated by results/make_extra.py; do not edit by hand.")

    o.c("bench/results/{higgs,bank,elec2}.json: keys of by_n_train (training sizes), dataset count")
    o.m("nDatasets", str(len(MAIN)))
    sizes = set()
    for name in res.glob("*.json"):
        sizes |= set(json.loads(name.read_text())["by_n_train"])
    for n in sorted(sizes, key=int):
        o.m(f"nSize{SIZE[n]}", intc(int(n)))

    o.c("bench/higgs.py: N_REF (reference rows), the low-level column count (np.arange(21)), all columns")
    o.m("nHgRefRows", intc(const(repo / "bench" / "higgs.py", "N_REF")))
    hg = (repo / "bench" / "higgs.py").read_text()
    o.m("nHgLowCols", re.search(r"low = np\.arange\((\d+)\)", hg).group(1))
    o.m("nHgAllCols", re.search(r"all (\d+) features", hg).group(1))
    o.c("bench/elec2.py: EMBARGO (rows between the reference's data and the training window)")
    o.m("nElEmbargo", str(const(repo / "bench" / "elec2.py", "EMBARGO")))

    o.c("bench/common/metrics.py: ece() bins, top-decile tail quantile of |r|")
    met = (repo / "bench" / "common" / "metrics.py").read_text()
    o.m("nEceBins", re.search(r"def ece\(y, raw, bins=(\d+)\)", met).group(1))
    q = float(re.search(r"np\.quantile\(np\.abs\(r\), ([0-9.]+)\)", met).group(1))
    o.m("nTailPct", str(round(100 * (1 - q))))

    o.c("bench/results/SCOPE.md: the win rule |d| > k SE, numbered post-hoc variants, pre-registered checks,"
        " total compute")
    scope = (res / "SCOPE.md").read_text()
    o.m("nWinK", re.search(r"\|d\| > (\d+) SE", scope).group(1))
    o.m("nPostHocVariants", str(len(re.findall(r"^\d+\. \*\*", section(scope, "Variants"), re.M))))
    o.m("nPreregChecks", str(len(re.findall(r"^- ", section(scope, "Pre-registered checks"), re.M))))
    o.m("nComputeHours", re.search(r"([0-9.]+) h summed", scope).group(1))
    o.m("nThreads", re.search(r"(\d+) threads per process", scope).group(1))

    o.c("paper/figures/make.py: ci95() uses the t quantile at 0.975")
    o.m("nCIPct", "95")

    o.c("bench/common/arms.py: scale of the nearly free reference column (a4)")
    arms_src = (repo / "bench" / "common" / "arms.py").read_text()
    o.m("nFreeScale", str(int(float(re.search(r'\("a4_ref_feature_x100", ([0-9.]+)\)', arms_src).group(1)))))

    o.c("git: last commit touching the package, the benchmarks and the patch (results were produced from it)")
    sha = subprocess.run(["git", "-C", str(repo), "log", "-1", "--format=%h", "--", "anchorlogit",
                          "bench", "patches"], capture_output=True, text=True, check=True).stdout.strip()
    o.m("nCommit", sha)

    confirm(o, HERE / "confirm_1se.json")

    o.c("bench/results/PRIVATE_LINE.txt: the only sentence about the private application (verbatim)")
    o.m("privateLine", latex_escape((res / "PRIVATE_LINE.txt").read_text().strip()))

    Path(a.out).write_text(o.text())
    print(f"wrote {a.out}: {o.count} macros")


if __name__ == "__main__":
    main()
